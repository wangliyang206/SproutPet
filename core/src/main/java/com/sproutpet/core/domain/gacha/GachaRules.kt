package com.sproutpet.core.domain.gacha

import com.sproutpet.core.domain.incubation.BlindBoxEngine
import com.sproutpet.core.domain.pet.Rarity

/**
 * 抽蛋（盲盒）这门生意的规则中枢。
 *
 * ## 它解决的问题（docs/09 `U-13` / `G-13`）
 *
 * 修复前，[BlindBoxEngine] 的**概率与保底全都写好了**，但**"抽一次要花什么"在 13 份文档里是空白**：
 * - `ItemRegistry.blind_box` 声明了 `ItemSource.SHOP`，而 `shopPriceGold` / `shopPriceGem`
 *   **双双是 `null`** —— "商店有卖、但没价"，商店 UI 直接渲染不出来；
 * - 免费来源只有"新用户送 1 个"，`docs/11 §四 金币消耗表` 里根本没有盲盒这一项；
 * - 多连（十连 / 二十连 / 五十连）**从未被设计过**；
 * - `BlindBoxEngine` 也没有「距保底还剩 N 抽」的 helper ——
 *   ⚠️ 不对称的是灵兽保底有 `MutantPityRules.remainingToThreshold`，盲盒保底却没有，
 *   而 PRD §2.1 早已承诺保底进度"对用户可见"。
 *
 * ## 定位（本文件所有数字的推导依据）
 *
 * **抽卡 = 素材供给，生育 = 上限路径。**
 * 灵兽不可抽（**ADR-017** 红线）—— 所以抽蛋最多只能把你送到"有素材去配对"，
 * 抽不到的东西只能靠生育。加抽卡**不改变**生育是上限路径这件事。
 *
 * 本作是「治愈陪伴」而非抽卡游戏，因此门票走**「陪伴换抽」，不走「钱换抽」**：
 * 每天认真照顾宠物就有 2 抽；金币只是"想多抽一枚"的补票口，而且**日限 1**。
 *
 * ## 平衡锚点（唯一的硬关系）
 *
 * ```
 * 每日免费抽数 × 30 天 ÷ 每只史诗+的期望抽数(9.6) ≈ 6.25 只
 * ```
 *
 * 即**一个月慢慢填满「家在册 6 只」**（`docs/00 §4.1`）——
 * 而不是开服三天抽满、之后 30 天都在看重复宠。
 * 这条锚点由单测守住：改门票或改概率而忘了另一边，测试会立刻变红。
 *
 * @see docs/00-产品需求文档PRD.md §2.1
 * @see docs/06-物种与稀有度设计.md §2.2
 * @see docs/11-经济系统设计.md §四
 */
object GachaRules {

    // ═══════════════════════ 免费门票：陪伴换抽 ═══════════════════════

    /** 每日签到赠送的抽数（零门槛，保证"每天回来就有"的确定性收益） */
    const val SIGN_IN_DRAW = 1

    /**
     * 日常任务**全部完成**（全清）额外赠送的抽数。
     *
     * 刻意挂在"全清"而非"完成任意一个"上：它让抽蛋成为**照顾宠物的副产品**，
     * 而不是一个可以独立于宠物刷的日常。任务数见 `EconomyRules.DailyTask.COUNT`。
     */
    const val ALL_TASKS_DRAW = 1

    /** 每日免费抽数合计（签到 1 + 任务全清 1） */
    const val FREE_DRAWS_PER_DAY = SIGN_IN_DRAW + ALL_TASKS_DRAW

    /** 免费抽数的 30 天累计（用于核对"一个月填满家"的节奏锚点） */
    const val FREE_DRAWS_PER_MONTH = FREE_DRAWS_PER_DAY * 30

    // ═══════════════════════ 付费门票 ═══════════════════════

    /**
     * 盲盒的金币售价。
     *
     * ⚠️ **这个数字是"唯一定义处"** —— `ItemRegistry.blind_box.shopPriceGold`
     * 引用它，而不是各写一份。修复前那里是 `null`（"商店有卖、但没价"）。
     *
     * 300 / 1,010（日收入上限）≈ 0.3 天：**当天收入就能补 1 抽**，但**日限 1** 锁死了上限，
     * 所以"有钱就能无限抽"不成立 —— 抽卡的仪式感不会被钱抹平。
     */
    const val GOLD_PRICE_PER_BOX = 300

    /** 盲盒的钻石售价（硬货币通道：愿意付费的人不必等每日免费额度） */
    const val GEM_PRICE_PER_BOX = 60

    /** 用金币购买盲盒的**日限**（个）—— 防止付费通道把抽卡变成"充钱就完事" */
    const val MAX_GOLD_PURCHASE_PER_DAY = 1

    /** 盲盒道具 id（`ItemRegistry` 中的键） */
    const val BOX_ITEM_ID = "blind_box"

    // ═══════════════════════ 多连 ═══════════════════════

    /** 一个连抽批次的抽数 */
    const val TEN_PULL = 10

    /**
     * 单次最多能连抽多少。
     *
     * **只做十连，不做二十 / 五十连** —— 理由是代价：
     * 五十连（50 × 300 = **15,000 金币**）≈ **15 天**的日收入上限，
     * 而「家在册」只有 **6 个名额**（`docs/00 §4.1`）—— 抽出来也放不下。
     * 劝人攒半个月只为一次连抽，与「治愈陪伴」的日常节奏是反的。
     */
    const val MAX_BATCH = TEN_PULL

    /**
     * 十连的最低保障档位：整批里**至少一只「稀有及以上」**。
     *
     * ⚠️ **刻意只保到「稀有」，不保「史诗」** —— 这是本文件最该被看见的一条：
     * 保「稀有」几乎免费（史诗+ 产出率 9.968% → 9.968%，只把 1.21% 的"十连全普通"消掉，+0.34%），
     * 而保「史诗」会把史诗+ 产出率从 **9.97% 抬到 13.47%（+35%）**，
     * 直接稀释 `docs/00 §4.1` 刚建立的三层稀缺结构。
     *
     * 数值依据：`tools/acquisition_sim.py` 第八节（40 万次蒙卡）。
     */
    val TEN_PULL_FLOOR: Rarity = Rarity.RARE

    // ═══════════════════════ 抽数 / 概率（公示口径） ═══════════════════════

    /**
     * 「史诗及以上」的**综合概率**（含保底）。
     *
     * ⚠️ **上架公示要披露的是这个数，不是基础概率 9.968%。**
     * 中国区合规要求披露**含保底的综合概率**；写基础概率属于少报。
     *
     * 数值依据：`tools/acquisition_sim.py` 第八节（40 万次蒙卡，保底实际触发率 4.77%）。
     */
    const val COMPREHENSIVE_EPIC_PLUS_RATE = 0.1042f

    /** 「史诗及以上」的基础（单抽）概率，即未计保底时的权重分布 */
    const val BASE_EPIC_PLUS_RATE = 0.09968f

    /**
     * 到达第一只「史诗及以上」的**期望抽数**（含保底）。
     *
     * 用于核对免费节奏：`FREE_DRAWS_PER_MONTH / 9.6 ≈ 6.25 只/月`。
     */
    const val EXPECTED_DRAWS_TO_EPIC_PLUS = 9.6

    /** 到达第一只「传说及以上」的期望抽数（**无任何保底通道**） */
    const val EXPECTED_DRAWS_TO_LEGENDARY_PLUS = 45.6

    /** 到达第一只「神话」的期望抽数（**无任何保底通道**，中位 222 抽） */
    const val EXPECTED_DRAWS_TO_MYTHIC = 320.4

    /**
     * 保底机制的口径（转发自 [BlindBoxEngine]，**不在本文件重复定义数值**）。
     */
    val PITY_THRESHOLD: Int get() = BlindBoxEngine.PITY_THRESHOLD

    /**
     * 距离下一次保底还剩几抽（供 UI 显示"距史诗保底还差 12 抽"）。
     *
     * 与 `MutantPityRules.remainingToThreshold`（灵兽保底的同款能力）对称 ——
     * 这条不对称曾经存在过（盲盒保底没有 helper，而 PRD 已承诺进度可见）。
     */
    fun remainingToPity(pityCount: Int): Int = BlindBoxEngine.remainingToPity(pityCount)

    // ═══════════════════════ 概率公示的必含条款 ═══════════════════════

    /**
     * 概率公示的**必含条款**（合规底线）。
     *
     * 放在 core 而不是资源文件里，是为了让它**可被测试**：
     * 任何一次"顺手把公示删短一点"都会让 `GachaRulesTest` 变红。
     * 展示时仍应走 `strings.xml`，但**内容以此为准**。
     */
    object Disclosure {

        /**
         * 最容易漏、也最反直觉的两条 —— 必须原样出现在公示里。
         *
         * 不写清楚的后果不是"少写一行字"，而是玩家会形成
         * **"抽多了总会出神话"的错误预期**（神话期望 **320 抽**、中位 **222 抽**，
         * 且有 **21% 的人 500 抽内拿不到**）。
         */
        val MUST_STATE: List<String> = listOf(
            "保底只到「史诗」：每 30 抽内必出一只史诗及以上。",
            "保底触发后计数归零 —— 因此它对「传说 / 神话」没有帮助，只是打断了连抽。",
            "「传说」与「神话」没有保底通道，只能靠自然概率（神话期望约 320 抽）。",
            "公示的概率为含保底的综合概率：史诗及以上 10.42%。",
            "灵兽（第 6 档）不可抽取，只能通过配对生育获得。"
        )
    }
}
